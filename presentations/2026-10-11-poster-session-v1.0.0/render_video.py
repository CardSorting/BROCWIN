"""Mix measured local speech segments, caption them, and encode the poster video.

All visuals are static authored documents or retained archival stills. No runtime
footage or experimental action is generated by this script.
"""
from pathlib import Path
from datetime import datetime, timezone
import json
from functools import lru_cache
import math
import re
import shutil
import subprocess
import textwrap
import wave
import sys

HERE = Path(__file__).resolve().parent
DATA = json.loads((HERE / 'session.json').read_text(encoding='utf-8'))
UTTERANCES = json.loads((HERE / 'utterances.json').read_text(encoding='utf-8'))


def save(name, data):
    (HERE / name).write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')


def stamp(seconds, vtt=False):
    total = int(round(seconds * 1000))
    hours, remainder = divmod(total, 3600000)
    minutes, remainder = divmod(remainder, 60000)
    secs, millis = divmod(remainder, 1000)
    return f'{hours:02d}:{minutes:02d}:{secs:02d}' + ('.' if vtt else ',') + f'{millis:03d}'


def mix():
    wav_paths = [HERE / x['wav'] for x in UTTERANCES]
    with wave.open(str(wav_paths[0]), 'rb') as first:
        channels, width, rate = first.getnchannels(), first.getsampwidth(), first.getframerate()
    assert (channels, width) == (1, 2), 'Expected local 16-bit mono synthesized speech'
    utterance_times = []
    scene_times = []
    sample_cursor = 0

    with wave.open(str(HERE / 'narration-raw.wav'), 'wb') as out:
        out.setnchannels(channels)
        out.setsampwidth(width)
        out.setframerate(rate)

        def silence(seconds):
            nonlocal sample_cursor
            frames = int(round(seconds * rate))
            out.writeframes(b'\0' * frames * channels * width)
            sample_cursor += frames

        for scene in DATA['scenes']:
            scene_start = sample_cursor / rate
            silence(0.55 if scene['id'] == '01' else 0.18)
            group = [u for u in UTTERANCES if u['scene'] == scene['id']]
            for u in group:
                with wave.open(str(HERE / u['wav']), 'rb') as src:
                    assert (src.getnchannels(), src.getsampwidth(), src.getframerate()) == (channels, width, rate)
                    frames = src.getnframes()
                    assert frames > 0
                    raw = src.readframes(frames)
                start = sample_cursor / rate
                out.writeframes(raw)
                sample_cursor += frames
                utterance_times.append({**u, 'startRaw': start, 'endRaw': sample_cursor / rate})
                silence(0.075 if u['role'] == 'Dr. GPT' else 0.27)
            silence(3.5 if scene['id'] == '28' else 0.85)
            scene_times.append({'scene': scene['id'], 'title': scene['title'], 'startRaw': scene_start, 'endRaw': sample_cursor / rate, 'visual': 'slides/scene-' + scene['id'] + '.png'})

    raw_duration = sample_cursor / rate
    target = DATA['targetSeconds']
    factor = raw_duration / target
    assert .65 <= factor <= 1.45, f'Pacing adjustment too large: {factor}'
    print(f'Raw narration plus holds: {raw_duration:.3f} s; target: {target} s; atempo factor: {factor:.6f}', flush=True)
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', 'narration-raw.wav', '-af', f'atempo={factor:.10f},apad,atrim=duration={target},loudnorm=I=-16:TP=-1.5:LRA=11', '-ar', '48000', '-ac', '1', 'narration.wav'], cwd=HERE, check=True)
    for u in utterance_times:
        u['start'], u['end'] = u['startRaw'] / factor, u['endRaw'] / factor
    for s in scene_times:
        s['start'], s['end'] = s['startRaw'] / factor, s['endRaw'] / factor
    scene_times[-1]['end'] = target
    save('timeline.json', {'targetSeconds': target, 'rawDurationSeconds': raw_duration, 'atempoFactor': factor, 'pacingMethod': 'Uniform pitch-preserving time adjustment of the full narration and holds', 'sceneBoundaryMethod': 'Measured WAV sample counts, scaled by the recorded factor', 'scenes': scene_times, 'utterances': utterance_times})
    captions(utterance_times, target)
    frames = ['ffconcat version 1.0']
    for s in scene_times:
        frames += ["file '" + s['visual'] + "'", 'duration ' + f"{s['end'] - s['start']:.9f}"]
    frames += ["file '" + scene_times[-1]['visual'] + "'"]
    (HERE / 'visuals.ffconcat').write_text('\n'.join(frames) + '\n', encoding='utf-8')
    words = len(re.findall(r'\S+', ' '.join(u['captionText'] for u in UTTERANCES)))
    return {'rawDurationSeconds': raw_duration, 'targetSeconds': target, 'atempoFactor': factor, 'words': words, 'averageWordsPerMinuteIncludingHolds': words / target * 60, 'sourceSampleRate': rate, 'mixedSampleRate': 48000}


def captions(utterances, target):
    cues = []
    previous_role = None
    for u in utterances:
        text = u['captionText']
        if u['role'] != previous_role:
            text = ('Audience: ' if u['role'] == 'Audience' else 'Dr. GPT: ') + text
        previous_role = u['role']
        groups = balanced_caption_groups(text)
        weights = [len(x.replace('\n', ' ')) for x in groups]
        total_weight = sum(weights)
        cursor = u['start']
        for i, group in enumerate(groups):
            end = u['end'] if i == len(groups) - 1 else cursor + (u['end'] - u['start']) * weights[i] / total_weight
            cues.append({'index': len(cues) + 1, 'utterance': u['id'], 'scene': u['scene'], 'role': u['role'], 'start': cursor, 'end': end, 'text': group})
            cursor = end
    srt = []
    vtt = ['WEBVTT', '']
    for c in cues:
        srt += [str(c['index']), stamp(c['start']) + ' --> ' + stamp(c['end']), c['text'], '']
        vtt += [str(c['index']), stamp(c['start'], True) + ' --> ' + stamp(c['end'], True), c['text'], '']
    (HERE / 'captions.srt').write_text('\n'.join(srt) + '\n', encoding='utf-8')
    (HERE / 'captions.vtt').write_text('\n'.join(vtt) + '\n', encoding='utf-8')
    save('caption-timing.json', {'method': 'Measured utterance boundaries; character-proportional subdivisions within an utterance', 'maxLines': 2, 'maxCharactersPerLine': 42, 'durationSeconds': target, 'cues': cues})
    print(f'Caption cues: {len(cues)}', flush=True)


def balanced_caption_groups(text):
    """Balance cue lengths so a final word does not become a flashing cue."""
    words = text.split()
    for count in range(max(1, math.ceil(len(text) / 76)), len(words) + 1):
        target_length = len(text) / count

        @lru_cache(None)
        def partition(position, remaining):
            if remaining == 0:
                return (0, ()) if position == len(words) else None
            best = None
            for end in range(position + 1, len(words) + 1):
                raw = ' '.join(words[position:end])
                lines = textwrap.wrap(raw, width=42, break_long_words=False, break_on_hyphens=False)
                if len(lines) > 2 or len(raw) > 84:
                    break
                next_part = partition(end, remaining - 1)
                if next_part is None:
                    continue
                cost = (len(raw) - target_length) ** 2 + next_part[0]
                choice = (cost, ('\n'.join(lines),) + next_part[1])
                if best is None or cost < best[0]:
                    best = choice
            return best

        result = partition(0, count)
        if result is not None:
            return list(result[1])
    raise ValueError('Could not wrap caption text')


def main():
    for binary in ['ffmpeg', 'ffprobe']:
        assert shutil.which(binary), f'{binary} must be installed'
    if '--captions-only' in sys.argv:
        timeline = json.loads((HERE / 'timeline.json').read_text(encoding='utf-8'))
        captions(timeline['utterances'], timeline['targetSeconds'])
        return
    if '--encode-only' in sys.argv:
        timeline = json.loads((HERE / 'timeline.json').read_text(encoding='utf-8'))
        pacing = {k: timeline[k] for k in ['rawDurationSeconds', 'targetSeconds', 'atempoFactor']}
    else:
        pacing = mix()
    # The SRT-to-ASS converter uses a 288-line coordinate system: 11 points
    # renders at roughly 41 pixels in this 1080-line output, within the safe area.
    style = 'FontName=Arial,FontSize=11,Alignment=2,MarginV=10,Outline=0,Shadow=0,PrimaryColour=&H00FFFFFF,BackColour=&H00382C12,BorderStyle=3'
    timeline = json.loads((HERE / 'timeline.json').read_text(encoding='utf-8'))
    chapters = [';FFMETADATA1', 'title=BROCWIN Research Poster Session']
    for scene in timeline['scenes']:
        chapters += ['[CHAPTER]', 'TIMEBASE=1/1000', 'START=' + str(round(scene['start'] * 1000)), 'END=' + str(round(scene['end'] * 1000)), 'title=' + scene['title']]
    (HERE / 'chapters.ffmetadata').write_text('\n'.join(chapters) + '\n', encoding='utf-8')
    command = ['ffmpeg', '-hide_banner', '-loglevel', 'warning', '-nostats', '-y', '-f', 'concat', '-safe', '0', '-i', 'visuals.ffconcat', '-i', 'narration.wav', '-f', 'ffmetadata', '-i', 'chapters.ffmetadata', '-map', '0:v:0', '-map', '1:a:0', '-map_metadata', '2', '-map_chapters', '2', '-vf', f"fps=24,subtitles=captions.srt:force_style='{style}'", '-c:v', 'libx264', '-preset', 'veryfast', '-tune', 'stillimage', '-crf', '23', '-threads', '2', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '160k', '-t', str(DATA['targetSeconds']), '-movflags', '+faststart', '-metadata', 'title=BROCWIN Ontological Introduction and Research Poster Session', '-metadata', 'comment=Synthesized presenter and simulated Q&A. Retained archival stills; no new game footage. White paper 1.0.1.', '-progress', 'encode-progress.txt', 'brocwin-poster-session.mp4']
    print('Encoding captioned 1920 × 1080 poster-session video.', flush=True)
    subprocess.run(command, cwd=HERE, check=True)
    probe = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-show_format', '-show_streams', '-show_chapters', '-of', 'json', 'brocwin-poster-session.mp4'], cwd=HERE))
    save('video-production-record.json', {'createdUtc': datetime.now(timezone.utc).isoformat(), 'method': 'Narrated static poster session and archived stills; synthesized voices and simulated Q&A', 'runtimeOrServiceLaunch': False, 'newExperimentalFootage': False, 'pacing': pacing, 'command': command, 'container': probe, 'openCaptions': True})
    print('Finished video: ' + probe['format']['duration'] + ' seconds', flush=True)


if __name__ == '__main__':
    main()
